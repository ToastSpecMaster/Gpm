'use strict';
const fs=require('fs'),vm=require('vm'),assert=require('assert');
const app=fs.readFileSync('app.js','utf8');
const hist=fs.readFileSync('historical-seasons-0109.js','utf8');
const patch=fs.readFileSync('historical-transfers-01095.js','utf8');
const html=fs.readFileSync('index.html','utf8');
const pkg=JSON.parse(fs.readFileSync('package.json','utf8'));
assert.match(app,/applyHistoricalTransferEvents01095\(c,round\)/,'historical event hook runs after each race');
assert.match(html,/historical-transfers-01095\.js/,'historical transfer patch loads');
assert.strictEqual(pkg.version,'0.10.11');
assert.strictEqual(pkg.gpmBuildVersion,'0.10.11.0');
assert(pkg.build.files.includes('historical-transfers-01095.js'));
const sandbox={window:{},console};
vm.createContext(sandbox);
sandbox.window.juniorDrivers=y=>y===2026?[{name:'Rafael Câmara',series:'F2',rating:84}]:[];
vm.runInContext(patch,sandbox);
const juniors=sandbox.window.juniorDrivers;
assert(!juniors(2016).some(d=>d.name==='Rafael Câmara'),'2016 feeder grid excludes Rafael Câmara');
assert(juniors(2016).some(d=>d.name==='Pierre Gasly'&&d.series==='GP2'),'2016 uses authentic GP2-era series');
assert(juniors(2017).some(d=>d.name==='Charles Leclerc'&&d.series==='F2'),'2017 F2 contains Charles Leclerc');
assert(juniors(2026).some(d=>d.name==='Rafael Câmara'&&d.series==='F2'),'2026 feeder list preserved');
const c={season:2016,round:4,name:'My Team',roster:{'Red Bull Racing':['Daniel Ricciardo','Daniil Kvyat'],'Toro Rosso':['Carlos Sainz','Max Verstappen']},drivers:['Driver A','Driver B'],history:[],driverChampPoints:{}};
sandbox.window.applyHistoricalTransferEvents01095(c,4);
assert.deepStrictEqual(Array.from(c.roster['Red Bull Racing']),['Daniel Ricciardo','Max Verstappen']);
assert.deepStrictEqual(Array.from(c.roster['Toro Rosso']),['Carlos Sainz','Daniil Kvyat']);
assert.strictEqual(c.history.length,1);
sandbox.window.applyHistoricalTransferEvents01095(c,4);
assert.strictEqual(c.history.length,1,'event cannot apply twice');
const r={season:2019,round:12,name:'My Team',roster:{'Red Bull Racing':['Max Verstappen','Pierre Gasly'],'Toro Rosso':['Daniil Kvyat','Alexander Albon']},drivers:['A','B'],history:[]};
sandbox.window.applyHistoricalTransferEvents01095(r,12);
assert.deepStrictEqual(Array.from(r.roster['Red Bull Racing']),['Max Verstappen','Alexander Albon']);
assert.deepStrictEqual(Array.from(r.roster['Toro Rosso']),['Daniil Kvyat','Pierre Gasly']);
const y25={season:2025,round:2,name:'My Team',roster:{'Red Bull Racing':['Max Verstappen','Liam Lawson'],'Racing Bulls':['Yuki Tsunoda','Isack Hadjar']},drivers:['A','B'],history:[]};
sandbox.window.applyHistoricalTransferEvents01095(y25,2);
assert.deepStrictEqual(Array.from(y25.roster['Red Bull Racing']),['Max Verstappen','Yuki Tsunoda']);
assert.deepStrictEqual(Array.from(y25.roster['Racing Bulls']),['Liam Lawson','Isack Hadjar']);
console.log('0.10.9.5 historical-transfer QA passed: correct feeder-era lists, no 2026 prospect leakage into 2016, 2016 Verstappen/Kvyat swap, 2019 Albon/Gasly swap, duplicate prevention, package inclusion.');
